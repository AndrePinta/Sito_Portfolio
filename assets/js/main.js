function mediaUrl(source) {
  return location.protocol === "file:"
    ? new URL(source.replace(/^\//, ""), location.href).href
    : new URL(source.replace(/^assets\/media\//, ""), R2_MEDIA_BASE).href;
}

function localMediaUrl(source) {
  return location.protocol === "file:"
    ? new URL(source.replace(/^\//, ""), location.href).href
    : new URL(source.replace(/^\//, ""), `${location.origin}/`).href;
}

function setMediaSource(media, source) {
  media.dataset.assetSource = source;
  media.src = mediaUrl(source);
}

document.addEventListener("error", (event) => {
  const media = event.target;
  if (!(media instanceof HTMLImageElement || media instanceof HTMLVideoElement)
      || location.protocol === "file:" || !media.dataset.assetSource
      || media.src !== mediaUrl(media.dataset.assetSource)) return;
  media.src = localMediaUrl(media.dataset.assetSource);
  delete media.dataset.assetSource;
}, true);


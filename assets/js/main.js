function playFlip(before, duration = 850) {
  if (reducedMotion.matches) return;
  cards.forEach((card) => {
    const old = before.get(card);
    if (!old || !card.isConnected) return;
    card.getAnimations().forEach((animation) => animation.cancel());
    if (getComputedStyle(card).display === "none") return;
    const next = card.getBoundingClientRect();
    if (!next.width || !next.height) return;
    if (!old.width || !old.height) {
      card.animate([
        { opacity: 0, transform: "translateY(12px) scale(.98)" },
        { opacity: 1, transform: "translateY(0) scale(1)" }
      ], { duration, easing: "cubic-bezier(.76, 0, .24, 1)" });
      return;
    }
    const dx = old.left - next.left;
    const dy = old.top - next.top;
    const sx = old.width / next.width;
    const sy = old.height / next.height;
    if (Math.abs(dx) + Math.abs(dy) + Math.abs(sx - 1) + Math.abs(sy - 1) < 0.02) return;
    card.animate([
      { transform: `translate(${dx}px, ${dy}px) scale(${sx}, ${sy})` },
      { transform: "translate(0, 0) scale(1, 1)" }
    ], { duration, easing: "cubic-bezier(.76, 0, .24, 1)" });
  });
}

function playCaptionFlip(before, duration = 850) {
  if (reducedMotion.matches) return;
  caption.getAnimations().forEach((animation) => animation.cancel());
  const next = caption.getBoundingClientRect();
  const dx = before.left - next.left;
  const dy = before.top - next.top;
  if (Math.abs(dx) + Math.abs(dy) < 1) return;
  caption.animate([
    { transform: `translate(${dx}px, ${dy}px)` },
    { transform: "translate(0, 0)" }
  ], { duration, easing: "cubic-bezier(.76, 0, .24, 1)" });
}

function playMobileDetailFlip(duration = 700) {
  if (reducedMotion.matches) return;
  const next = detail.getBoundingClientRect();
  if (!next.width || !next.height) return;
  detail.getAnimations().forEach((animation) => animation.cancel());
  detail.animate([
    { clipPath: "inset(0 0 100% 0)", opacity: .7 },
    { clipPath: "inset(0)", opacity: 1 }
  ], { duration, easing: "cubic-bezier(.76, 0, .24, 1)" });
}

function setRoute(path, options = {}) {
  const { push = true, replace = false, restoreScroll = false, animate = true, revealContact = false } = options;
  const currentRouteVersion = ++routeVersion;
  const route = getView(path);
  const previousView = stage.dataset.view;
  const heroToProject = !mobileLayout.matches && previousView === "hero" && route.view === "project";
  const mobileFocusBefore = mobileLayout.matches && route.view === "project"
    && previousView === "project"
    ? cards.find((card) => card.dataset.slug === route.project.slug)?.getBoundingClientRect()
    : null;
  const useViewTransition = animate && !mobileLayout.matches && !reducedMotion.matches
    && typeof document.startViewTransition === "function";
  const captionMovesBetweenHeroAndProject = useViewTransition && matchMedia("(min-width: 781px)").matches
    && ((stage.dataset.view === "hero" && route.view === "project")
      || (stage.dataset.view === "project" && route.view === "hero"));
  const root = document.documentElement;
  root.classList.toggle("caption-to-project", captionMovesBetweenHeroAndProject);
  root.classList.toggle("hero-to-project", heroToProject && useViewTransition);
  const captionStart = captionMovesBetweenHeroAndProject ? caption.getBoundingClientRect() : null;
  const before = animate && !useViewTransition
    ? new Map(cards.map((card) => [card, card.getBoundingClientRect()]))
    : null;
  const captionBefore = before ? caption.getBoundingClientRect() : null;
  const update = () => {
    if (route.view !== "hero") hideContact();
    const previousCard = cards.find((card) => card.classList.contains("is-selected"));
    if (previousCard) {
      const previousProject = projects.find((project) => project.slug === previousCard.dataset.slug);
      showCardArtwork(previousCard, previousProject, false);
    }
    if (location.pathname !== path) {
      if (replace) history.replaceState({ view: route.view }, "", path);
      else if (push) history.pushState({ view: route.view }, "", path);
    }
    if (route.view === "project") {
      if (stage.dataset.view === "list") savedListScroll = window.scrollY;
      updateCaption(route.project, false);
      cards.forEach((card) => card.classList.toggle("is-selected", card.dataset.slug === route.project.slug));
      const selectedCard = cards.find((card) => card.dataset.slug === route.project.slug);
      if (!mobileLayout.matches) showCardArtwork(selectedCard, route.project, true);
      renderDetail(route.project);
      stage.dataset.view = "project";
      stage.dataset.project = route.project.slug;
      document.body.classList.add("is-in-project");
      placeDetail(selectedCard);
      if (mobileFocusBefore && selectedCard) {
        const focusShift = selectedCard.getBoundingClientRect().top - mobileFocusBefore.top;
        if (focusShift) {
          window.scrollTo({ top: Math.max(0, window.scrollY + focusShift), behavior: "instant" });
        }
      }
      if (!mobileLayout.matches) window.scrollTo({ top: 0, behavior: "instant" });
    } else {
      cards.forEach((card) => card.classList.remove("is-selected"));
      stage.dataset.view = route.view;
      delete stage.dataset.project;
      document.body.classList.remove("is-in-project");
      placeDetail(null);
      galleryObserver?.disconnect();
      detail.replaceChildren();
      if (route.view === "hero") updateCaption(projects[0], false);
      if (restoreScroll) window.scrollTo({ top: savedListScroll, behavior: "instant" });
      else if (route.view === "list" || route.view === "hero") {
        window.scrollTo({ top: 0, behavior: "instant" });
      }
    }
    updateDocument(route.project, route.view);
    updateHeroLayout();
    updatePanorama();
    if (revealContact && route.view === "hero" && desktopContact.matches) showContact();
    if (captionStart) {
      const end = caption.getBoundingClientRect();
      root.style.setProperty("--caption-from-x", `${captionStart.left}px`);
      root.style.setProperty("--caption-from-y", `${captionStart.top}px`);
      root.style.setProperty("--caption-to-x", `${end.left}px`);
      root.style.setProperty("--caption-to-y", `${end.top}px`);
      root.style.setProperty("--caption-transition-width", `${Math.max(captionStart.width, end.width)}px`);
      root.style.setProperty("--caption-transition-height", `${Math.max(captionStart.height, end.height)}px`);
    }
  };

  if (useViewTransition) {
    const transition = document.startViewTransition(update);
    if (captionMovesBetweenHeroAndProject || heroToProject) {
      transition.finished.then(() => {
        if (routeVersion !== currentRouteVersion) return;
        if (captionMovesBetweenHeroAndProject) root.classList.remove("caption-to-project");
        if (heroToProject) root.classList.remove("hero-to-project");
      });
    }
  } else {
    update();
    if (before) {
      requestAnimationFrame(() => {
        playFlip(before);
        if (mobileLayout.matches && route.view === "project") {
          playMobileDetailFlip();
        }
        playCaptionFlip(captionBefore);
      });
    }
  }
}

